-- TrolleyMap schema (Supabase / Postgres)
create table if not exists public.trolley_reports (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  brand text check (char_length(brand) <= 40),
  note text check (char_length(note) <= 500),
  suburb text check (char_length(suburb) <= 80),
  photo text check (char_length(photo) <= 400000),
  status text not null default 'reported' check (status in ('reported','collected')),
  collected_at timestamptz,
  demo boolean not null default false
);
alter table public.trolley_reports enable row level security;
create policy trolley_read on public.trolley_reports for select to anon, authenticated using (true);
create policy trolley_insert on public.trolley_reports for insert to anon, authenticated
  with check (status = 'reported' and demo = false);

create or replace function public.trolley_mark_collected(report_id bigint)
returns void language sql security definer set search_path = public as $$
  update public.trolley_reports set status = 'collected', collected_at = now()
  where id = report_id and status = 'reported';
$$;
grant execute on function public.trolley_mark_collected(bigint) to anon, authenticated;
